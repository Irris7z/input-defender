"use strict";
const {readFileSync, writeFileSync} = require("node:fs");
const {join} = require("node:path");
const root = join(__dirname, "../extension");
// Each execution world gets its own self-contained entry point, independent of injection ordering.
for (const [out, entry] of [["main-world.js", "monitor.js"], ["isolated-world.js", "bridge.js"]]) {
  const parts = (entry === "bridge.js" ? ["core.js", "ui-text.js", entry] : ["core.js", entry]).map(name => readFileSync(join(root, name), "utf8"));
  writeFileSync(join(root, out), "// Generated by scripts/build.cjs. Edit core.js / " + entry + " instead.\n" + parts.join("\n;\n"));
}
